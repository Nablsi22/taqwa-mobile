#!/usr/bin/env python3
"""Generates lib/features/supervisor/presentation/welcome/slogan_calligraphy_data.dart.

«إلهي أنت مقصودي ورضاك مطلوبي» is shaped with HarfBuzz in Aref Ruqaa Bold (the
font the app already ships) and every glyph's outline is exported as SVG path
data, so the welcome screen can draw the words stroke by stroke, the way a
calligrapher writes them.

The two lines form one panel: the second line sits 0.82 em under the first and
0.18 em to its right, so the tall strokes of «ط» and «ك» rise into the gaps of
the line above — an interlaced composition, but every word stays legible.

    pip install uharfbuzz fonttools
    python3 tool/gen_slogan_calligraphy.py

References
  HarfBuzz shaping   https://harfbuzz.github.io/
  fontTools pens     https://fonttools.readthedocs.io/en/latest/pens/
  Aref Ruqaa (OFL)   https://github.com/alif-type/aref-ruqaa
"""
import pathlib

import uharfbuzz as hb
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / 'assets/fonts/ArefRuqaa-Bold.ttf'
OUT = ROOT / 'lib/features/supervisor/presentation/welcome/slogan_calligraphy_data.dart'
LINES = ['إلهي أنت مقصودي', 'ورضاك مطلوبي']
LINE_STEP_EM = 0.82
SECOND_LINE_SHIFT_EM = 0.18


def main() -> None:
    face = hb.Face(hb.Blob.from_file_path(str(FONT)))
    font = hb.Font(face)
    tt = TTFont(str(FONT))
    glyph_set = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    upem = tt['head'].unitsPerEm

    shaped = []
    for text in LINES:
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(font, buf, {})
        x, items = 0, []
        for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
            items.append((order[info.codepoint], x + pos.x_offset, pos.y_offset))
            x += pos.x_advance
        shaped.append((items, x))

    widest = max(width for _, width in shaped)
    glyphs = []
    for line, (items, width) in enumerate(shaped):
        dx = (widest - width) / 2 + (SECOND_LINE_SHIFT_EM * upem if line else 0)
        base_y = line * LINE_STEP_EM * upem
        for name, gx, gy in items:
            pen = DecomposingRecordingPen(glyph_set)
            # Font units are y-up; the canvas is y-down.
            glyph_set[name].draw(TransformPen(pen, (1, 0, 0, -1, gx + dx, base_y - gy)))
            if pen.value:
                glyphs.append((line, pen.value))

    points = [p for _, ops in glyphs for _, args in ops for p in args]
    x0 = min(p[0] for p in points)
    y0 = min(p[1] for p in points)
    width = max(p[0] for p in points) - x0
    height = max(p[1] for p in points) - y0

    def fmt(p):
        return f'{p[0] - x0:.0f} {p[1] - y0:.0f}'

    def svg(ops):
        out = []
        for op, args in ops:
            if op == 'moveTo':
                out.append('M' + fmt(args[0]))
            elif op == 'lineTo':
                out.append('L' + fmt(args[0]))
            elif op == 'qCurveTo':
                # TrueType runs of off-curve points imply on-curve midpoints.
                pts = list(args)
                for i in range(len(pts) - 1):
                    end = pts[i + 1] if i == len(pts) - 2 else (
                        (pts[i][0] + pts[i + 1][0]) / 2, (pts[i][1] + pts[i + 1][1]) / 2)
                    out.append('Q' + fmt(pts[i]) + ' ' + fmt(end))
            elif op == 'curveTo':
                out.append('C' + ' '.join(fmt(p) for p in args))
            elif op in ('closePath', 'endPath'):
                out.append('Z')
        return ''.join(out)

    def right_edge(ops):
        return max(p[0] for _, args in ops for p in args)

    # Writing order: first line, then second; right to left within a line.
    glyphs.sort(key=lambda g: (g[0], -right_edge(g[1])))

    rows = '\n'.join(f"  ({line}, '{svg(ops)}')," for line, ops in glyphs)
    OUT.write_text(f'''// GENERATED by tool/gen_slogan_calligraphy.py — do not edit by hand.
//
// «إلهي أنت مقصودي ورضاك مطلوبي» as the glyph outlines of Aref Ruqaa Bold
// (assets/fonts/ArefRuqaa-Bold.ttf, SIL Open Font License 1.1), shaped with
// HarfBuzz and laid out as one panel whose second line reaches up into the
// first. Coordinates are font units with y pointing down; glyphs are listed in
// writing order (first line, then second; right to left within each line).

/// Size of the panel, in font units.
const double kSloganWidth = {width:.0f};
const double kSloganHeight = {height:.0f};

/// (line, SVG path data). The path data uses only absolute M, L, Q and Z.
const List<(int, String)> kSloganGlyphs = [
{rows}
];
''', encoding='utf-8')
    print(f'{len(glyphs)} glyphs, {width:.0f}x{height:.0f} units -> {OUT}')


if __name__ == '__main__':
    main()
