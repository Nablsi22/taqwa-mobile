library;

class Dhikr {
  final String id;
  final String text;        // Arabic text of the dhikr
  final String? reference;  // Hadith reference
  final int repeatCount;    // How many times to recite
  final String? benefit;    // Reward / benefit

  const Dhikr({
    required this.id,
    required this.text,
    this.reference,
    this.repeatCount = 1,
    this.benefit,
  });
}

class AzkarCategory {
  final String id;
  final String name;
  final String icon;        // Emoji or icon code
  final String description;
  final List<Dhikr> adhkar;

  const AzkarCategory({
    required this.id,
    required this.name,
    required this.icon,
    required this.description,
    required this.adhkar,
  });
}

